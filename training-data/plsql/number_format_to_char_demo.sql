-- TO_CHAR / TO_NUMBER format models.
DECLARE
    v_amount NUMBER := 1234567.891;
BEGIN
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(v_amount, '9,999,999.99'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(v_amount, 'FM9,999,999.00'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(42, '00000'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(0.5, 'FM0.00'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(255, 'XXXX'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(-15, 'S999'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(1234.5, 'L9,999.99'));
    DBMS_OUTPUT.PUT_LINE(TO_NUMBER('1,234.50', '9,999.99') + 1);
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(12345, 'FM99999EEEE'));
    DBMS_OUTPUT.PUT_LINE(ROUND(v_amount, -3) || ' ' || TRUNC(v_amount, 1));
END;
/
