SET SERVEROUTPUT ON
CREATE OR REPLACE PACKAGE fmt IS
  FUNCTION show(p_val NUMBER) RETURN VARCHAR2;
  FUNCTION show(p_val DATE) RETURN VARCHAR2;
  FUNCTION show(p_val BOOLEAN) RETURN VARCHAR2;
END fmt;
/
CREATE OR REPLACE PACKAGE BODY fmt IS
  FUNCTION show(p_val NUMBER) RETURN VARCHAR2 IS
  BEGIN RETURN 'num:' || p_val; END;
  FUNCTION show(p_val DATE) RETURN VARCHAR2 IS
  BEGIN RETURN 'date:' || TO_CHAR(p_val, 'YYYY-MM-DD'); END;
  FUNCTION show(p_val BOOLEAN) RETURN VARCHAR2 IS
  BEGIN RETURN CASE WHEN p_val THEN 'yes' ELSE 'no' END; END;
END fmt;
/
BEGIN
  DBMS_OUTPUT.PUT_LINE(fmt.show(42));
  DBMS_OUTPUT.PUT_LINE(fmt.show(DATE '2024-01-15'));
  DBMS_OUTPUT.PUT_LINE(fmt.show(TRUE));
END;
/
