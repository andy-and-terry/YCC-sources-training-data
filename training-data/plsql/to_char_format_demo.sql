CREATE OR REPLACE PROCEDURE to_char_format_demo IS
    n NUMBER := 1234567.891;
BEGIN
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(n, '9,999,999.99'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(n, 'FM9,999,999.00'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(42, '00000'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(0.5, 'FM0.00'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(255, 'XXXX'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(-15, 'S999'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(12345, '99999EEEE'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(DATE '2024-07-04', 'FMDay, DD Month YYYY'));
    DBMS_OUTPUT.PUT_LINE(TO_NUMBER('1,234.50', '9,999.99'));
END to_char_format_demo;
/
