DECLARE
    v_start DATE := DATE '2024-01-31';
BEGIN
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(v_start + 10, 'YYYY-MM-DD'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(ADD_MONTHS(v_start, 1), 'YYYY-MM-DD'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(LAST_DAY(v_start), 'DD'));
    DBMS_OUTPUT.PUT_LINE(MONTHS_BETWEEN(DATE '2024-06-15', DATE '2024-03-15'));
    DBMS_OUTPUT.PUT_LINE(TO_CHAR(NEXT_DAY(v_start, 'MONDAY'), 'Day DD-Mon'));
    DBMS_OUTPUT.PUT_LINE(DATE '2024-03-01' - DATE '2024-02-01');
END;
/
