fib <- function(n) if (n < 2) n else fib(n - 1) + fib(n - 2)
print(sapply(0:10, fib))
fact <- function(n) if (n <= 1) 1 else n * fact(n - 1)
print(fact(10))
gcd <- function(a, b) if (b == 0) a else gcd(b, a %% b)
print(gcd(48, 18))
binsearch <- function(v, t) { lo <- 1; hi <- length(v); while (lo <= hi) { mid <- (lo + hi) %/% 2; if (v[mid] == t) return(mid); if (v[mid] < t) lo <- mid + 1 else hi <- mid - 1 }; -1 }
print(binsearch(c(1, 3, 5, 7, 9), 7))
qsort <- function(v) if (length(v) <= 1) v else { p <- v[1]; r <- v[-1]; c(qsort(r[r < p]), p, qsort(r[r >= p])) }
print(qsort(c(3, 6, 1, 8, 2, 9, 2)))
hanoi <- function(n, from = "A", to = "C", via = "B") if (n == 0) 0 else hanoi(n - 1, from, via, to) + 1 + hanoi(n - 1, via, to, from)
print(hanoi(8))
is_prime <- function(n) n > 1 && all(n %% 2:max(2, floor(sqrt(n))) != 0 | n == 2)
print(Filter(is_prime, 1:30))
perms <- function(v) if (length(v) <= 1) list(v) else do.call(c, lapply(seq_along(v), function(i) lapply(perms(v[-i]), function(p) c(v[i], p))))
print(length(perms(1:4)))
collatz <- function(n, steps = 0) if (n == 1) steps else collatz(if (n %% 2 == 0) n / 2 else 3 * n + 1, steps + 1)
print(collatz(27))
