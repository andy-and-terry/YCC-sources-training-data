setClass("Shape", representation("VIRTUAL", name = "character"))
setClass("Circle", contains = "Shape", representation(r = "numeric"), prototype(name = "circle"),
  validity = function(object) if (object@r < 0) "radius must be non-negative" else TRUE)
setClass("Rect", contains = "Shape", representation(w = "numeric", h = "numeric"), prototype(name = "rect"))
setGeneric("area", function(shape, ...) standardGeneric("area"))
setMethod("area", "Circle", function(shape, ...) pi * shape@r^2)
setMethod("area", "Rect", function(shape, ...) shape@w * shape@h)
setMethod("show", "Shape", function(object) cat("<", object@name, "area", round(area(object), 2), ">\n"))
shapes <- list(new("Circle", r = 1), new("Rect", w = 2, h = 3))
for (s in shapes) print(s)
print(is(shapes[[1]], "Shape")); print(isVirtualClass("Shape")); print(existsMethod("area", "Circle"))
print(tryCatch(new("Circle", r = -1), error = function(e) "invalid circle"))
setMethod("+", signature("Rect", "Rect"), function(e1, e2) new("Rect", w = e1@w + e2@w, h = e1@h + e2@h))
print(area(shapes[[2]] + shapes[[2]]))
c1 <- shapes[[1]]; c1@r <- 3; print(c1@r); print(slotNames("Rect"))
