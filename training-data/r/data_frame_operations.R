print(df[df$pay > 15, ])
print(subset(df, dept == "x", select = c(name, pay)))
df$bonus <- df$pay * 0.1
print(head(df, 2))
print(aggregate(pay ~ dept, data = df, FUN = sum))
print(tapply(df$pay, df$dept, mean))
print(df[order(-df$pay), "name"])
print(nrow(df)); print(ncol(df)); print(colnames(df))
print(merge(df, data.frame(dept = c("x", "y"), boss = c("P", "Q"))))
