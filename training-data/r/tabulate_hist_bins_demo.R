set.seed(1)
x <- round(rnorm(50, 50, 10))
h <- hist(x, breaks = seq(0, 100, 20), plot = FALSE)
print(h$counts)
print(h$mids)
bins <- cut(x, breaks = seq(0, 100, 20), right = FALSE)
print(table(bins))
print(levels(bins))
print(tabulate(findInterval(x, seq(0, 100, 20)), nbins = 5))
dens <- density(x)
print(class(dens))
print(round(h$density[1:3], 4))
for (i in seq_along(h$counts)) cat(sprintf("%3d-%3d | %s\n", h$breaks[i], h$breaks[i + 1], strrep("#", h$counts[i])))
