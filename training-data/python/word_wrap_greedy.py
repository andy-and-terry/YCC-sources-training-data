def wrap(text, width):
    lines, line = [], ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    if line:
        lines.append(line)
    return lines


for l in wrap("the quick brown fox jumps over the lazy dog", 15):
    print(f"|{l:<15}|")
