def duval(s: str) -> list[str]:
    out, i, n = [], 0, len(s)
    while i < n:
        j, k = i + 1, i
        while j < n and s[k] <= s[j]:
            k = i if s[k] < s[j] else k + 1
            j += 1
        while i <= k:
            out.append(s[i:i + j - k])
            i += j - k
    return out


print(duval("banana"))
