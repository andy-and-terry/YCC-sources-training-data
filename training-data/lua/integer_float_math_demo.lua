-- Lua 5.3+ distinguishes integer and float subtypes.
print(math.type(1), math.type(1.0), math.type("1"))
print(10 / 2, 10 // 2, 10.0 // 3, 10 % 3, -10 % 3)
print(7 // 2, -7 // 2, 7 % -3)
print(3 | 4, 7 & 2, 5 ~ 1, ~0, 1 << 4, 256 >> 4)
print(2 ^ 10, 2 ^ 0.5)
print(math.maxinteger, math.mininteger)
print(math.maxinteger + 1 == math.mininteger)
print(math.tointeger(3.0), math.tointeger(3.5), math.tointeger("8"))
print(1 == 1.0, math.ult(1, -1))
print(math.floor(3.7), math.ceil(3.2), math.floor(-3.5))
print(math.abs(-4), math.max(1, 9, 3), math.min(4, 2))
print(math.fmod(-7, 3), -7 % 3)
print(string.format("%.1f", 0.1 + 0.2), 0.1 + 0.2 == 0.3)
print(tostring(1e15), tostring(2^53), 1e100)
print(tonumber("0x1F"), tonumber("  12  "), tonumber("1e2"), tonumber("z", 36), tonumber("abc"))
print(math.huge, -math.huge, math.huge // 1)
local nan = 0 / 0
print(nan ~= nan)
print(8 // 0.0, pcall(function() return 8 // 0 end))
