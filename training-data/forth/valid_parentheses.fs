VARIABLE SP
0 SP !

: PUSH ( c -- ) SP @ CELLS STACK + ! SP @ 1+ SP ! ;
: POP ( -- c ) SP @ 1- SP ! SP @ CELLS STACK + @ ;

: VALID-PARENS? ( addr len -- flag )
  0 SP !
  TRUE -ROT
  OVER + SWAP
  BEGIN
    2DUP <
  WHILE
    DUP C@
    CASE
      [CHAR] ( OF PUSH ENDOF
      [CHAR] [ OF PUSH ENDOF
      [CHAR] { OF PUSH ENDOF
      [CHAR] ) OF SP @ 0= IF ROT DROP FALSE -ROT ELSE POP [CHAR] ( <> IF ROT DROP FALSE -ROT THEN THEN ENDOF
      [CHAR] ] OF SP @ 0= IF ROT DROP FALSE -ROT ELSE POP [CHAR] [ <> IF ROT DROP FALSE -ROT THEN THEN ENDOF
      [CHAR] } OF SP @ 0= IF ROT DROP FALSE -ROT ELSE POP [CHAR] { <> IF ROT DROP FALSE -ROT THEN THEN ENDOF
    ENDCASE
    1+
  REPEAT
  2DROP SP @ 0= AND ;

S" {[()]}" VALID-PARENS? .
S" {[(])}" VALID-PARENS? .
