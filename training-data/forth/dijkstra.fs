5 CONSTANT NODES
999999 CONSTANT INF
CREATE GRAPH NODES NODES * CELLS ALLOT
CREATE DIST NODES CELLS ALLOT
CREATE VISITED NODES CELLS ALLOT

: GRAPH@ ( from to -- addr ) SWAP NODES * + CELLS GRAPH + ;
: DIST@ ( n -- addr ) CELLS DIST + ;
: VISITED@ ( n -- addr ) CELLS VISITED + ;

: SET-EDGE ( from to weight -- )
  ROT ROT GRAPH@ ! ;

: INIT ( -- )
  NODES NODES * 0 DO INF I CELLS GRAPH + ! LOOP
  NODES 0 DO INF I DIST@ ! 0 I VISITED@ ! LOOP ;

: MIN-UNVISITED ( -- node )
  -1 INF
  NODES 0 DO
    I VISITED@ @ 0= IF
      I DIST@ @ OVER > IF
        DROP I DIST@ @ SWAP I
      THEN
    THEN
  LOOP
  DROP ;

: DIJKSTRA ( source -- )
  DIST@ 0 SWAP !
  NODES 0 DO
    MIN-UNVISITED
    DUP -1 = IF DROP LEAVE THEN
    DUP 1 SWAP VISITED@ !
    DUP >R
    NODES 0 DO
      R@ I GRAPH@ @ INF <> IF
        R@ DIST@ @ R@ I GRAPH@ @ +
        I DIST@ @ MIN I DIST@ !
      THEN
    LOOP
    R> DROP
  LOOP ;

