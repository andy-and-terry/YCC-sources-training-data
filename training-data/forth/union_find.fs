CREATE PARENT 6 CELLS ALLOT
6 CONSTANT NODES
VARIABLE CUR
VARIABLE ROOT-A
VARIABLE ROOT-B

: PARENT-ADDR ( node -- addr ) CELLS PARENT + ;

: INIT-UF ( -- )
  NODES 0 DO I I PARENT-ADDR ! LOOP ;

: FIND ( node -- root )
  CUR !
  BEGIN
    CUR @ PARENT-ADDR @ CUR @ <>
  WHILE
    CUR @ PARENT-ADDR @ CUR !
  REPEAT
  CUR @ ;

: UNION ( a b -- )
  FIND ROOT-B !
  FIND ROOT-A !
  ROOT-A @ ROOT-B @ <> IF
    ROOT-B @ ROOT-A @ PARENT-ADDR !
  THEN ;

: CONNECTED? ( a b -- flag )
  FIND SWAP FIND = ;

INIT-UF
0 1 UNION
1 2 UNION
3 4 UNION
0 2 CONNECTED? . CR
0 3 CONNECTED? . CR
3 4 CONNECTED? . CR
