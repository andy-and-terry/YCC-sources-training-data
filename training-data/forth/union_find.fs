10 CONSTANT MAX-NODES
CREATE PARENT-ARR MAX-NODES CELLS ALLOT

: PARENT@ ( n -- addr ) CELLS PARENT-ARR + ;

: INIT-UF ( -- )
  MAX-NODES 0 DO I I PARENT@ ! LOOP ;

: FIND ( n -- root )
  BEGIN
    DUP PARENT@ @ OVER <>
  WHILE
    PARENT@ @
  REPEAT ;

: UNION ( a b -- )
  FIND SWAP FIND
  2DUP = IF 2DROP EXIT THEN
  PARENT@ ! ;

: CONNECTED? ( a b -- flag )
  FIND SWAP FIND = ;

