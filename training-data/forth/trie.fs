26 CONSTANT ALPHA-SIZE
80 CONSTANT MAX-NODES

CREATE CHILD ALPHA-SIZE MAX-NODES * CELLS ALLOT
CREATE IS-WORD MAX-NODES CELLS ALLOT
VARIABLE NODE-COUNT
VARIABLE NEW-NODE-ID
VARIABLE SADDR
VARIABLE SLEN
VARIABLE CUR-NODE
VARIABLE CHAR-IDX

: CHILD-ADDR ( node char-idx -- addr )
  SWAP ALPHA-SIZE * + CELLS CHILD + ;

: IS-WORD-ADDR ( node -- addr ) CELLS IS-WORD + ;

: NEW-NODE ( -- node )
  NODE-COUNT @ NEW-NODE-ID !
  NEW-NODE-ID @ IS-WORD-ADDR 0 SWAP !
  ALPHA-SIZE 0 DO
    NEW-NODE-ID @ I CHILD-ADDR -1 SWAP !
  LOOP
  1 NODE-COUNT +!
  NEW-NODE-ID @ ;

: INIT-TRIE ( -- )
  0 NODE-COUNT !
  NEW-NODE DROP ;

: TRIE-INSERT ( addr len -- )
  SLEN ! SADDR !
  0 CUR-NODE !
  SLEN @ 0 DO
    SADDR @ I + C@ [CHAR] a - CHAR-IDX !
    CUR-NODE @ CHAR-IDX @ CHILD-ADDR @ -1 = IF
      CUR-NODE @ CHAR-IDX @ CHILD-ADDR
      NEW-NODE SWAP !
    THEN
    CUR-NODE @ CHAR-IDX @ CHILD-ADDR @ CUR-NODE !
  LOOP
  CUR-NODE @ IS-WORD-ADDR 1 SWAP ! ;

: TRIE-CONTAINS ( addr len -- found? )
  SLEN ! SADDR !
  0 CUR-NODE !
  SLEN @ 0 DO
    SADDR @ I + C@ [CHAR] a - CHAR-IDX !
    CUR-NODE @ CHAR-IDX @ CHILD-ADDR @
    DUP -1 = IF
      DROP UNLOOP FALSE EXIT
    THEN
    CUR-NODE !
  LOOP
  CUR-NODE @ IS-WORD-ADDR @ 1 = ;

INIT-TRIE
S" cat" TRIE-INSERT
S" car" TRIE-INSERT
S" card" TRIE-INSERT
S" dog" TRIE-INSERT

S" cat" TRIE-CONTAINS .
S" car" TRIE-CONTAINS .
S" ca" TRIE-CONTAINS .
S" card" TRIE-CONTAINS .
S" dogs" TRIE-CONTAINS .
