CREATE ARR 4 , 2 , 2 , 8 , 3 , 3 , 1 , 0 ,
8 CONSTANT ARR-LEN
9 CONSTANT RANGE
CREATE COUNTS RANGE CELLS ALLOT
CREATE OUT ARR-LEN CELLS ALLOT

: ELEM ( i -- addr ) CELLS ARR + ;
: COUNT-ELEM ( i -- addr ) CELLS COUNTS + ;
: OUT-ELEM ( i -- addr ) CELLS OUT + ;

VARIABLE OUT-POS

: CLEAR-COUNTS ( -- )
  RANGE 0 DO 0 I COUNT-ELEM ! LOOP ;

: TALLY ( -- )
  ARR-LEN 0 DO
    I ELEM @ COUNT-ELEM DUP @ 1+ SWAP !
  LOOP ;

: EMIT-VALUE ( value count -- )
  0 ?DO
    DUP OUT-POS @ OUT-ELEM !
    OUT-POS @ 1+ OUT-POS !
  LOOP
  DROP ;

: BUILD-OUTPUT ( -- )
  0 OUT-POS !
  RANGE 0 DO
    I I COUNT-ELEM @ EMIT-VALUE
  LOOP ;

: PRINT-ARR ( -- )
  ARR-LEN 0 DO I OUT-ELEM @ . LOOP ;

CLEAR-COUNTS
TALLY
BUILD-OUTPUT
PRINT-ARR
CR
