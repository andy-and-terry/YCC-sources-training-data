: PRIME? ( n -- f )
  DUP 2 < IF DROP FALSE EXIT THEN
  TRUE SWAP
  DUP 1+ 2 ?DO
    DUP I I * < IF LEAVE THEN
    DUP I MOD 0= IF NIP FALSE SWAP LEAVE THEN
  LOOP
  DROP ;

: REV ( n -- r ) 0 SWAP BEGIN DUP WHILE 10 /MOD >R 10 * R> + SWAP REPEAT DROP ;

: EMIRPS 100 2 DO
    I PRIME? I REV I <> AND I REV PRIME? AND IF I . THEN
  LOOP CR ;
