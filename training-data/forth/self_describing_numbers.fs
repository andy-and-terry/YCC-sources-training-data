  DROP ;

: SELF-DESCRIBING? ( addr len -- flag )
  LEN ! ADDR !
  LEN @ 0 ?DO
    I COUNT-DIGIT  ADDR @ I + C@ [CHAR] 0 - <> IF FALSE UNLOOP EXIT THEN
