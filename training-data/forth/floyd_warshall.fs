CREATE DIST NODES NODES * CELLS ALLOT

: DIST@ ( row col -- addr ) SWAP NODES * + CELLS DIST + ;

: INIT ( -- )
  NODES NODES * 0 DO INF I CELLS DIST + ! LOOP
  NODES 0 DO I I DIST@ 0 SWAP ! LOOP ;

: SET-EDGE ( from to weight -- )
  ROT ROT DIST@ ! ;

: FLOYD-WARSHALL ( -- )
  NODES 0 DO
    NODES 0 DO
      NODES 0 DO
        J I DIST@ @
        J K DIST@ @ K I DIST@ @ +
        MIN
        J I DIST@ !
      LOOP
    LOOP
  LOOP ;

