CREATE NEXT-ARR 10 CELLS ALLOT
CREATE VAL-ARR 10 CELLS ALLOT
VARIABLE FREE-PTR
VARIABLE HEAD

: NEXT-ADDR ( node -- addr ) CELLS NEXT-ARR + ;
: VAL-ADDR ( node -- addr ) CELLS VAL-ARR + ;

: INIT-LIST ( -- )
  0 FREE-PTR !
  -1 HEAD ! ;

: PUSH-FRONT ( value -- )
  FREE-PTR @
  DUP VAL-ADDR ROT SWAP !
  DUP NEXT-ADDR HEAD @ SWAP !
  HEAD !
  1 FREE-PTR +! ;

: PRINT-LIST ( -- )
  HEAD @
  BEGIN
    DUP -1 <>
  WHILE
    DUP VAL-ADDR @ .
    NEXT-ADDR @
  REPEAT
  DROP ;

INIT-LIST
1 PUSH-FRONT
2 PUSH-FRONT
3 PUSH-FRONT
PRINT-LIST
CR
