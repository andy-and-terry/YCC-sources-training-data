CREATE COINS 1 , 3 , 4 ,
3 CONSTANT NUM-COINS
11 CONSTANT TARGET
999999 CONSTANT INF
CREATE DP TARGET 1+ CELLS ALLOT
VARIABLE AMOUNT
VARIABLE BEST
VARIABLE CAND

: COIN@ ( i -- addr ) CELLS COINS + ;
: DP@ ( amt -- addr ) CELLS DP + ;

: INIT ( -- )
  0 0 DP@ !
  TARGET 0 DO INF I 1+ DP@ ! LOOP ;

: TRY-COIN ( coin-index -- )
  COIN@ @
  DUP AMOUNT @ > IF DROP EXIT THEN
  AMOUNT @ SWAP - DP@ @
  DUP INF <> IF
    1+ BEST @ MIN BEST !
  ELSE
    DROP
  THEN ;

: COIN-CHANGE ( -- )
  INIT
  TARGET 1+ 1 DO
    I AMOUNT !
    INF BEST !
    NUM-COINS 0 DO
      I TRY-COIN
    LOOP
    BEST @ AMOUNT @ DP@ !
  LOOP ;

COIN-CHANGE
TARGET DP@ @ . CR
