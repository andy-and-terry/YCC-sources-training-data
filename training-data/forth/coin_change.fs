CREATE COINS 1 , 3 , 4 ,
3 CONSTANT NCOINS
11 CONSTANT AMOUNT
CREATE DP AMOUNT 1+ CELLS ALLOT
999999 CONSTANT INF
VARIABLE AMT
VARIABLE CIDX

: DP-ADDR ( i -- addr ) CELLS DP + ;
: COIN@ ( i -- coin ) CELLS COINS + @ ;

: INIT-DP ( -- )
  AMOUNT 1+ 0 DO INF I DP-ADDR ! LOOP
  0 0 DP-ADDR ! ;

: TRY-COIN ( -- )
  CIDX @ COIN@ AMT @ > IF EXIT THEN
  AMT @ CIDX @ COIN@ - DP-ADDR @ INF = IF EXIT THEN
  AMT @ CIDX @ COIN@ - DP-ADDR @ 1+
  AMT @ DP-ADDR @
  MIN
  AMT @ DP-ADDR ! ;

: COIN-CHANGE ( -- min-coins )
  INIT-DP
  AMOUNT 1+ 1 DO
    I AMT !
    NCOINS 0 DO
      I CIDX !
      TRY-COIN
    LOOP
  LOOP
  AMOUNT DP-ADDR @ ;

COIN-CHANGE . CR
