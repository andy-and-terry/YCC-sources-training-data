4 CONSTANT CAPACITY
CREATE KEY-ARR CAPACITY CELLS ALLOT
CREATE VAL-ARR CAPACITY CELLS ALLOT
CREATE TICK-ARR CAPACITY CELLS ALLOT
VARIABLE COUNT
VARIABLE CLOCK

: KEY@ ( i -- addr ) CELLS KEY-ARR + ;
: VAL@ ( i -- addr ) CELLS VAL-ARR + ;
: TICK@ ( i -- addr ) CELLS TICK-ARR + ;

: INIT-CACHE ( -- )
  0 COUNT ! 0 CLOCK ! ;

: FIND-SLOT ( key -- idx )
  -1
  COUNT @ 0 DO
    OVER I KEY@ @ = IF DROP I THEN
  LOOP
  NIP ;

: OLDEST-SLOT ( -- idx )
  0
  COUNT @ 1 DO
    I TICK@ @ OVER TICK@ @ < IF I THEN
  LOOP ;

: CACHE-PUT ( key value -- )
  1 CLOCK +!
  SWAP FIND-SLOT
  DUP -1 <> IF
    2DUP VAL@ ! DROP
    CLOCK @ SWAP TICK@ !
  ELSE
    DROP
    COUNT @ CAPACITY < IF
      COUNT @ DUP 1 COUNT +!
    ELSE
      OLDEST-SLOT
    THEN
    SWAP OVER KEY@ ! DUP CLOCK @ SWAP TICK@ ! VAL@ !
  THEN ;

: CACHE-GET ( key -- value found? )
  FIND-SLOT
  DUP -1 = IF DROP 0 0 EXIT THEN
  1 CLOCK +!
  DUP CLOCK @ SWAP TICK@ !
  VAL@ @ -1 ;

INIT-CACHE
1 10 CACHE-PUT
2 20 CACHE-PUT
1 CACHE-GET . .
3 30 CACHE-PUT
4 40 CACHE-PUT
2 CACHE-GET . .
CR
