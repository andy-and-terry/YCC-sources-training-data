\ Reserving memory with CREATE and ALLOT

CREATE BUFFER 16 ALLOT

: FILL-BUFFER ( -- )
  16 0 DO I 10 * BUFFER I + C! LOOP ;

: DUMP-BUFFER ( -- )
  16 0 DO BUFFER I + C@ . LOOP CR ;

FILL-BUFFER
DUMP-BUFFER
BUFFER 16 255 FILL
DUMP-BUFFER
BUFFER 16 ERASE
DUMP-BUFFER

CREATE SQUARES 5 CELLS ALLOT
5 0 DO I I * SQUARES I CELLS + ! LOOP
5 0 DO SQUARES I CELLS + @ . LOOP CR
HERE 0 > . CR
