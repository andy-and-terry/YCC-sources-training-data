CREATE QBUF 8 CELLS ALLOT
8 CONSTANT QCAP
VARIABLE QHEAD
VARIABLE QCOUNT

: QELEM ( i -- addr ) CELLS QBUF + ;

: Q-INIT ( -- ) 0 QHEAD ! 0 QCOUNT ! ;

: ENQUEUE ( n -- )
  QHEAD @ QCOUNT @ + QCAP MOD QELEM !
  QCOUNT @ 1+ QCOUNT ! ;

: DEQUEUE ( -- n )
  QHEAD @ QELEM @
  QHEAD @ 1+ QCAP MOD QHEAD !
  QCOUNT @ 1- QCOUNT ! ;

Q-INIT
10 ENQUEUE
20 ENQUEUE
30 ENQUEUE
DEQUEUE .
DEQUEUE .
40 ENQUEUE
DEQUEUE .
DEQUEUE .
CR
