CREATE ADJ 36 CELLS ALLOT
6 CONSTANT NODES
CREATE VISITED 6 CELLS ALLOT
CREATE QUEUE 6 CELLS ALLOT
VARIABLE QHEAD
VARIABLE QTAIL
VARIABLE QCOUNT
VARIABLE CUR

: ADJ-ADDR ( from to -- addr ) SWAP NODES * + CELLS ADJ + ;
: GET-EDGE ( from to -- flag ) ADJ-ADDR @ ;
: VISITED? ( node -- flag ) CELLS VISITED + @ ;
: MARK-VISITED ( node -- ) CELLS VISITED + 1 SWAP ! ;

: INIT-GRAPH ( -- )
  36 0 DO 0 I CELLS ADJ + ! LOOP
  0 1 ADJ-ADDR 1 SWAP !
  0 2 ADJ-ADDR 1 SWAP !
  1 3 ADJ-ADDR 1 SWAP !
  2 3 ADJ-ADDR 1 SWAP !
  3 4 ADJ-ADDR 1 SWAP !
  4 5 ADJ-ADDR 1 SWAP ! ;

: ENQUEUE ( node -- )
  QTAIL @ CELLS QUEUE + !
  QTAIL @ 1+ NODES MOD QTAIL !
  1 QCOUNT +! ;

: DEQUEUE ( -- node )
  QHEAD @ CELLS QUEUE + @
  QHEAD @ 1+ NODES MOD QHEAD !
  -1 QCOUNT +! ;

: EMPTY? ( -- flag ) QCOUNT @ 0= ;

: BFS-FROM ( start -- )
  0 QHEAD ! 0 QTAIL ! 0 QCOUNT !
  NODES 0 DO 0 I CELLS VISITED + ! LOOP
  DUP MARK-VISITED
  ENQUEUE
  BEGIN
    EMPTY? 0=
  WHILE
    DEQUEUE CUR !
    CUR @ .
    NODES 0 DO
      CUR @ I GET-EDGE IF
        I VISITED? 0= IF
          I MARK-VISITED
          I ENQUEUE
        THEN
      THEN
    LOOP
  REPEAT ;

INIT-GRAPH
0 BFS-FROM
CR
