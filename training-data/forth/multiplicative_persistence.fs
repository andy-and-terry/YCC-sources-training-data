VARIABLE PRODUCT
VARIABLE STEPS

: DIGIT-PRODUCT ( n -- p )
  1 PRODUCT !
  BEGIN DUP 0> WHILE
    10 /MOD SWAP PRODUCT @ * PRODUCT !
  REPEAT
  DROP PRODUCT @ ;

: PERSISTENCE ( n -- steps )
  0 STEPS !
  BEGIN DUP 10 >= WHILE
    DIGIT-PRODUCT  1 STEPS +!
  REPEAT
  DROP STEPS @ ;

39 DUP . PERSISTENCE . CR
77 DUP . PERSISTENCE . CR
999 DUP . PERSISTENCE . CR
10 DUP . PERSISTENCE . CR
