8 CONSTANT BOARD-SIZE
CREATE QUEENS BOARD-SIZE CELLS ALLOT
VARIABLE SOLUTIONS
VARIABLE CUR-ROW
VARIABLE CUR-COL

: Q@ ( row -- col ) CELLS QUEENS + @ ;
: Q! ( row col -- ) SWAP CELLS QUEENS + ! ;

: SAFE? ( row col -- flag )
  CUR-COL !
  CUR-ROW !
  CUR-ROW @ 0 DO
    I Q@ CUR-COL @ = IF UNLOOP FALSE EXIT THEN
    I Q@ CUR-COL @ - ABS CUR-ROW @ I - ABS = IF UNLOOP FALSE EXIT THEN
  LOOP
  TRUE ;

: PLACE-QUEEN ( row -- )
  DUP BOARD-SIZE = IF
    DROP
    1 SOLUTIONS +!
  ELSE
    BOARD-SIZE 0 DO
      DUP I SAFE? IF
        DUP I Q!
        DUP 1+ PLACE-QUEEN
      THEN
    LOOP
    DROP
  THEN ;

0 SOLUTIONS !
0 PLACE-QUEEN
SOLUTIONS @ .
CR
