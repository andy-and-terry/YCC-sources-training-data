CREATE VAL-ARR 20 CELLS ALLOT
CREATE LEFT-ARR 20 CELLS ALLOT
CREATE RIGHT-ARR 20 CELLS ALLOT
VARIABLE FREE-PTR
VARIABLE TREE-ROOT
VARIABLE TARGET-VAL
VARIABLE CUR
VARIABLE PARENT
VARIABLE GO-LEFT

: VAL-ADDR ( node -- addr ) CELLS VAL-ARR + ;
: LEFT-ADDR ( node -- addr ) CELLS LEFT-ARR + ;
: RIGHT-ADDR ( node -- addr ) CELLS RIGHT-ARR + ;

: INIT-TREE ( -- )
  0 FREE-PTR !
  -1 TREE-ROOT ! ;

: NEW-NODE ( value -- node )
  >R
  FREE-PTR @
  DUP VAL-ADDR R@ SWAP !
  DUP LEFT-ADDR -1 SWAP !
  DUP RIGHT-ADDR -1 SWAP !
  R> DROP
  1 FREE-PTR +! ;

: FIND-SPOT ( -- )
  TREE-ROOT @ CUR !
  BEGIN
    CUR @ -1 <>
  WHILE
    CUR @ PARENT !
    CUR @ VAL-ADDR @ TARGET-VAL @ > IF
      TRUE GO-LEFT !
      PARENT @ LEFT-ADDR @ CUR !
    ELSE
      FALSE GO-LEFT !
      PARENT @ RIGHT-ADDR @ CUR !
    THEN
  REPEAT ;

: BST-INSERT ( value -- )
  TARGET-VAL !
  TREE-ROOT @ -1 = IF
    TARGET-VAL @ NEW-NODE TREE-ROOT !
  ELSE
    FIND-SPOT
    TARGET-VAL @ NEW-NODE
    GO-LEFT @ IF
      PARENT @ LEFT-ADDR !
    ELSE
      PARENT @ RIGHT-ADDR !
    THEN
  THEN ;

: CONTAINS ( value -- found? )
  TARGET-VAL !
  TREE-ROOT @
  BEGIN
    DUP -1 <>
  WHILE
    DUP VAL-ADDR @ TARGET-VAL @ = IF
      DROP TRUE EXIT
    THEN
    DUP VAL-ADDR @ TARGET-VAL @ > IF
      LEFT-ADDR @
    ELSE
      RIGHT-ADDR @
    THEN
  REPEAT
  DROP FALSE ;

: INORDER ( node -- )
  DUP -1 = IF DROP EXIT THEN
  DUP LEFT-ADDR @ RECURSE
  DUP VAL-ADDR @ .
  RIGHT-ADDR @ RECURSE ;

INIT-TREE
5 BST-INSERT
3 BST-INSERT
8 BST-INSERT
1 BST-INSERT
4 BST-INSERT
TREE-ROOT @ INORDER
CR
5 CONTAINS .
9 CONTAINS .
CR
