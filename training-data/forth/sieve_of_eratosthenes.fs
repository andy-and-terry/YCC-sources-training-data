50 CONSTANT LIMIT
CREATE FLAGS LIMIT 1+ ALLOT
FLAGS LIMIT 1+ 1 FILL

: MARK-COMPOSITE ( n -- )
  DUP DUP *
  BEGIN
    DUP LIMIT <=
  WHILE
    0 OVER FLAGS + C!
    OVER +
  REPEAT
  2DROP ;

: SIEVE ( -- )
  2 LIMIT 1+ 2 DO
    I FLAGS + C@ 0<> IF I MARK-COMPOSITE THEN
  LOOP ;

: PRINT-PRIMES ( -- )
  2 LIMIT 1+ 2 DO
    I FLAGS + C@ 0<> IF I . THEN
  LOOP ;

SIEVE
PRINT-PRIMES
CR
