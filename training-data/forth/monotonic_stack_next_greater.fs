CREATE ARR 4 , 5 , 2 , 25 , 7 , 8 ,
6 CONSTANT ARR-LEN
CREATE RESULT ARR-LEN CELLS ALLOT
CREATE STK ARR-LEN CELLS ALLOT
VARIABLE SP

: ELEM ( i -- addr ) CELLS ARR + ;
: RESULT-ELEM ( i -- addr ) CELLS RESULT + ;
: STK-ELEM ( i -- addr ) CELLS STK + ;
: PUSH ( n -- ) SP @ STK-ELEM ! 1 SP +! ;
: POP ( -- n ) -1 SP +! SP @ STK-ELEM @ ;
: STACK-TOP ( -- idx ) SP @ 1- STK-ELEM @ ;

: NEXT-GREATER ( -- )
  0 SP !
  ARR-LEN 0 DO
    BEGIN
      SP @ 0> IF STACK-TOP ELEM @ I ELEM @ < ELSE FALSE THEN
    WHILE
      POP I ELEM @ SWAP RESULT-ELEM !
    REPEAT
    I PUSH
  LOOP
  BEGIN SP @ 0> WHILE POP RESULT-ELEM -1 SWAP ! REPEAT ;

: PRINT-RESULTS ( -- )
  ARR-LEN 0 DO
    I RESULT-ELEM @ .
  LOOP ;

NEXT-GREATER
PRINT-RESULTS
CR
