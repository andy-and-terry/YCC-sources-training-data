CREATE ARR 170 , 45 , 75 , 90 , 802 , 24 , 2 , 66 ,
8 CONSTANT ARR-LEN
CREATE AUX 8 CELLS ALLOT
CREATE COUNTS 10 CELLS ALLOT
VARIABLE EXP
VARIABLE MAXVAL
VARIABLE IDX

: ELEM ( i -- addr ) CELLS ARR + ;
: AUX-ELEM ( i -- addr ) CELLS AUX + ;
: CNT ( d -- addr ) CELLS COUNTS + ;

: FIND-MAX ( -- )
  0 MAXVAL !
  ARR-LEN 0 DO
    I ELEM @ MAXVAL @ MAX MAXVAL !
  LOOP ;

: DIGIT-OF ( n -- d ) EXP @ / 10 MOD ;

: RESET-COUNTS ( -- )
  10 0 DO 0 I CNT ! LOOP ;

: TALLY-DIGITS ( -- )
  ARR-LEN 0 DO
    I ELEM @ DIGIT-OF CNT DUP @ 1+ SWAP !
  LOOP ;

: ACCUMULATE-COUNTS ( -- )
  10 1 DO
    I CNT @ I 1- CNT @ + I CNT !
  LOOP ;

: PLACE-STABLE ( -- )
  ARR-LEN 0 DO
    ARR-LEN 1- I - IDX !
    IDX @ ELEM @ DIGIT-OF CNT DUP @ 1- DUP >R SWAP !
    IDX @ ELEM @ R> AUX-ELEM !
  LOOP ;

: COPY-BACK ( -- )
  ARR-LEN 0 DO
    I AUX-ELEM @ I ELEM !
  LOOP ;

: COUNTING-PASS ( -- )
  RESET-COUNTS
  TALLY-DIGITS
  ACCUMULATE-COUNTS
  PLACE-STABLE
  COPY-BACK ;

: RADIX-SORT ( -- )
  FIND-MAX
  1 EXP !
  BEGIN
    EXP @ MAXVAL @ <=
  WHILE
    COUNTING-PASS
    EXP @ 10 * EXP !
  REPEAT ;

: PRINT-ARR ( -- )
  ARR-LEN 0 DO I ELEM @ . LOOP ;

RADIX-SORT
PRINT-ARR
CR
