CREATE ADJ 36 CELLS ALLOT
6 CONSTANT NODES
CREATE VISITED 6 CELLS ALLOT

: ADJ-ADDR ( from to -- addr ) SWAP NODES * + CELLS ADJ + ;
: GET-EDGE ( from to -- flag ) ADJ-ADDR @ ;
: VISITED? ( node -- flag ) CELLS VISITED + @ ;
: MARK-VISITED ( node -- ) CELLS VISITED + 1 SWAP ! ;

: INIT-GRAPH ( -- )
  36 0 DO 0 I CELLS ADJ + ! LOOP
  NODES 0 DO 0 I CELLS VISITED + ! LOOP
  0 1 ADJ-ADDR 1 SWAP !
  0 2 ADJ-ADDR 1 SWAP !
  1 3 ADJ-ADDR 1 SWAP !
  2 3 ADJ-ADDR 1 SWAP !
  3 4 ADJ-ADDR 1 SWAP !
  4 5 ADJ-ADDR 1 SWAP ! ;

: DFS-VISIT ( node -- )
  DUP VISITED? IF DROP EXIT THEN
  DUP MARK-VISITED
  DUP .
  NODES 0 DO
    DUP I GET-EDGE IF
      I RECURSE
    THEN
  LOOP
  DROP ;

INIT-GRAPH
0 DFS-VISIT
CR
