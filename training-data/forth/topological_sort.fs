6 CONSTANT TS-N
CREATE ADJ TS-N TS-N * CELLS ALLOT
CREATE INDEG TS-N CELLS ALLOT
CREATE QUEUE TS-N CELLS ALLOT
CREATE ORDER TS-N CELLS ALLOT
VARIABLE Q-HEAD
VARIABLE Q-TAIL
VARIABLE ORDER-COUNT
VARIABLE CUR-U
VARIABLE EDGE-U
VARIABLE EDGE-V
VARIABLE TMP-NODE

: ADJ@ ( u v -- addr ) SWAP TS-N * + CELLS ADJ + ;
: INDEG@ ( v -- addr ) CELLS INDEG + ;
: Q@ ( i -- addr ) CELLS QUEUE + ;
: ORDER@ ( i -- addr ) CELLS ORDER + ;

: TS-INIT ( -- )
  TS-N TS-N * 0 DO 0 I CELLS ADJ + ! LOOP
  TS-N 0 DO 0 I INDEG@ ! LOOP
  0 Q-HEAD ! 0 Q-TAIL ! 0 ORDER-COUNT ! ;

: ADD-EDGE ( u v -- )
  EDGE-V ! EDGE-U !
  EDGE-U @ EDGE-V @ ADJ@ 1 SWAP !
  EDGE-V @ INDEG@ DUP @ 1+ SWAP ! ;

: ENQUEUE ( node -- )
  TMP-NODE !
  Q-TAIL @ Q@ TMP-NODE @ SWAP !
  1 Q-TAIL +! ;

: DEQUEUE ( -- node )
  Q-HEAD @ Q@ @
  1 Q-HEAD +! ;

: TS-RUN ( -- )
  TS-N 0 DO
    I INDEG@ @ 0= IF I ENQUEUE THEN
  LOOP
  BEGIN
    Q-HEAD @ Q-TAIL @ <
  WHILE
    DEQUEUE CUR-U !
    ORDER-COUNT @ ORDER@ CUR-U @ SWAP !
    1 ORDER-COUNT +!
    TS-N 0 DO
      CUR-U @ I ADJ@ @ 1 = IF
        I INDEG@ DUP @ 1- SWAP !
        I INDEG@ @ 0= IF
          I ENQUEUE
        THEN
      THEN
    LOOP
  REPEAT ;

: PRINT-ORDER ( -- )
  TS-N 0 DO
    I ORDER@ @ .
  LOOP ;

TS-INIT
5 2 ADD-EDGE
5 0 ADD-EDGE
4 0 ADD-EDGE
4 1 ADD-EDGE
2 3 ADD-EDGE
3 1 ADD-EDGE

TS-RUN
PRINT-ORDER
CR
