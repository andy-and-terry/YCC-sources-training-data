CREATE ADJ 25 CELLS ALLOT
5 CONSTANT NODES
CREATE INDEG 5 CELLS ALLOT
CREATE QUEUE 5 CELLS ALLOT
CREATE ORDER 5 CELLS ALLOT
VARIABLE QHEAD
VARIABLE QTAIL
VARIABLE QCOUNT
VARIABLE ORDER-IDX

: ADJ-ADDR ( from to -- addr ) SWAP NODES * + CELLS ADJ + ;
: GET-EDGE ( from to -- flag ) ADJ-ADDR @ ;
: INDEG-ADDR ( node -- addr ) CELLS INDEG + ;

: INIT-GRAPH ( -- )
  NODES NODES * 0 DO 0 I CELLS ADJ + ! LOOP
  NODES 0 DO 0 I INDEG-ADDR ! LOOP
  0 2 ADJ-ADDR 1 SWAP !
  0 3 ADJ-ADDR 1 SWAP !
  1 3 ADJ-ADDR 1 SWAP !
  2 4 ADJ-ADDR 1 SWAP !
  3 4 ADJ-ADDR 1 SWAP !
  NODES 0 DO
    NODES 0 DO
      J I GET-EDGE IF
        I INDEG-ADDR DUP @ 1+ SWAP !
      THEN
    LOOP
  LOOP ;

: ENQUEUE ( node -- )
  QTAIL @ CELLS QUEUE + !
  QTAIL @ 1+ NODES MOD QTAIL !
  1 QCOUNT +! ;

: DEQUEUE ( -- node )
  QHEAD @ CELLS QUEUE + @
  QHEAD @ 1+ NODES MOD QHEAD !
  -1 QCOUNT +! ;

: EMPTY? ( -- flag ) QCOUNT @ 0= ;

: TOPO-SORT ( -- )
  0 QHEAD ! 0 QTAIL ! 0 QCOUNT ! 0 ORDER-IDX !
  NODES 0 DO
    I INDEG-ADDR @ 0= IF I ENQUEUE THEN
  LOOP
  BEGIN
    EMPTY? 0=
  WHILE
    DEQUEUE
    DUP ORDER-IDX @ CELLS ORDER + !
    1 ORDER-IDX +!
    NODES 0 DO
      DUP I GET-EDGE IF
        I INDEG-ADDR DUP @ 1- SWAP !
        I INDEG-ADDR @ 0= IF I ENQUEUE THEN
      THEN
    LOOP
    DROP
  REPEAT ;

INIT-GRAPH
TOPO-SORT
NODES 0 DO
  I CELLS ORDER + @ .
LOOP
CR
