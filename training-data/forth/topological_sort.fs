6 CONSTANT NODES
CREATE ADJ NODES NODES * CELLS ALLOT
CREATE INDEG NODES CELLS ALLOT
CREATE QUEUE NODES CELLS ALLOT
CREATE ORDER NODES CELLS ALLOT
VARIABLE QHEAD
VARIABLE QTAIL
VARIABLE OCOUNT

: ADJ@ ( from to -- addr ) SWAP NODES * + CELLS ADJ + ;
: INDEG@ ( n -- addr ) CELLS INDEG + ;
: QUEUE@ ( i -- addr ) CELLS QUEUE + ;
: ORDER@ ( i -- addr ) CELLS ORDER + ;

: ADD-EDGE ( from to -- )
  2DUP ADJ@ 1 SWAP !
  INDEG@ 1 SWAP +! ;

: INIT ( -- )
  NODES NODES * 0 DO 0 I CELLS ADJ + ! LOOP
  NODES 0 DO 0 I INDEG@ ! LOOP
  0 QHEAD ! 0 QTAIL ! 0 OCOUNT ! ;

: ENQUEUE ( n -- ) QTAIL @ QUEUE@ ! 1 QTAIL +! ;
: DEQUEUE ( -- n ) QHEAD @ QUEUE@ @ 1 QHEAD +! ;

: TOPO-SORT ( -- )
  NODES 0 DO I INDEG@ @ 0= IF I ENQUEUE THEN LOOP
  BEGIN
    QHEAD @ QTAIL @ <
  WHILE
    DEQUEUE
    DUP OCOUNT @ ORDER@ ! 1 OCOUNT +!
    NODES 0 DO
      2DUP I ADJ@ @ 1 = IF
        I INDEG@ -1 SWAP +!
        I INDEG@ @ 0= IF I ENQUEUE THEN
      THEN
    LOOP
    DROP
  REPEAT ;

INIT
5 2 ADD-EDGE
5 0 ADD-EDGE
4 0 ADD-EDGE
4 1 ADD-EDGE
2 3 ADD-EDGE
3 1 ADD-EDGE
TOPO-SORT
OCOUNT @ 0 DO I ORDER@ @ . LOOP
CR
