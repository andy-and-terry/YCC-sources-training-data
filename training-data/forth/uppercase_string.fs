CREATE BUF 32 ALLOT
VARIABLE SRC-ADDR
VARIABLE SRC-LEN

: UPPERCASE-STRING ( addr len -- )
  SRC-LEN !
  SRC-ADDR !
  SRC-LEN @ 0 DO
    SRC-ADDR @ I + C@
    DUP [CHAR] a [CHAR] z 1+ WITHIN IF 32 - THEN
    BUF I + C!
  LOOP
  BUF SRC-LEN @ TYPE ;

S" Hello World" UPPERCASE-STRING CR
S" forth rocks" UPPERCASE-STRING CR
