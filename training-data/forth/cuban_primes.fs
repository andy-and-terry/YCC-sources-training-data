: PRIME? ( n -- f )
  DUP 2 < IF DROP FALSE EXIT THEN
  TRUE SWAP
  DUP 1+ 2 ?DO
    DUP I I * < IF LEAVE THEN
    DUP I MOD 0= IF NIP FALSE SWAP LEAVE THEN
  LOOP
  DROP ;

: CUBAN ( y -- p ) DUP DUP * 3 * SWAP 3 * + 1+ ;

: CUBANS 0 1 BEGIN OVER 8 < WHILE
    DUP CUBAN DUP PRIME? IF . SWAP 1+ SWAP ELSE DROP THEN 1+
  REPEAT 2DROP CR ;
