7 CONSTANT SORTED-LEN
VARIABLE LOW
VARIABLE HIGH
VARIABLE TARGET
VARIABLE RESULT
VARIABLE DONE

: SEARCH ( target -- index )
  TARGET !
  0 LOW !
  SORTED-LEN 1- HIGH !
  -1 RESULT !
  0 DONE !
  BEGIN
    DONE @ 0= LOW @ HIGH @ <= AND
  WHILE
    LOW @ HIGH @ + 2/
    DUP CELLS SORTED + @
    DUP TARGET @ =
    IF
      DROP RESULT ! 1 DONE !
    ELSE
      TARGET @ >
      IF 1- HIGH ! ELSE 1+ LOW ! THEN
    THEN
  REPEAT
  RESULT @ ;

