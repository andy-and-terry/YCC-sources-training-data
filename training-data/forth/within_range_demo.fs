\ WITHIN, MIN, MAX and range checks

: IN-RANGE? ( n lo hi -- flag )
  1+ WITHIN ;

: CLAMP ( n lo hi -- n' )
  ROT MIN MAX ;

: SCORE-GRADE ( n -- )
  DUP 90 101 WITHIN IF DROP ." A" EXIT THEN
  DUP 80 90 WITHIN IF DROP ." B" EXIT THEN
  DUP 70 80 WITHIN IF DROP ." C" EXIT THEN
  DROP ." F" ;

