101 CONSTANT PRIME
256 CONSTANT BASE
VARIABLE PADDR
VARIABLE PLEN
VARIABLE TADDR
VARIABLE TLEN
VARIABLE PHASH
VARIABLE THASH
VARIABLE HIGH-POW
VARIABLE I-VAR

: PCHAR ( i -- c ) PADDR @ + C@ ;
: TCHAR ( i -- c ) TADDR @ + C@ ;

: COMPUTE-HASH ( addr len -- hash )
  0 SWAP
  0 DO
    OVER I + C@
    2 PICK PRIME MOD * +
    PRIME MOD
  LOOP
  NIP ;

: MATCHES-AT? ( pos -- flag )
  TRUE SWAP
  PLEN @ 0 DO
    OVER I + TCHAR I PCHAR <> IF DROP FALSE THEN
  LOOP
  NIP ;

: RABIN-KARP ( pattern-addr pattern-len text-addr text-len -- pos )
  TLEN ! TADDR ! PLEN ! PADDR !
  PADDR @ PLEN @ COMPUTE-HASH PHASH !
  TLEN @ PLEN @ - 1+ 0 MAX
  0 DO
    TADDR @ I + PLEN @ COMPUTE-HASH THASH !
    THASH @ PHASH @ = I MATCHES-AT? AND IF
      I UNLOOP EXIT
    THEN
  LOOP
  -1 ;

S" AB" S" XXABXX" RABIN-KARP . CR
S" XYZ" S" ABCDEF" RABIN-KARP . CR
