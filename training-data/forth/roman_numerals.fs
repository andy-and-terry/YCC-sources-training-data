: PRINT-N-TIMES ( n c -- )
  SWAP 0 DO DUP EMIT LOOP DROP ;

: TO-ROMAN ( n -- )
  BEGIN DUP 1000 >= WHILE 1000 - CHAR M EMIT REPEAT
  BEGIN DUP 900 >= WHILE 900 - S" CM" TYPE REPEAT
  BEGIN DUP 500 >= WHILE 500 - CHAR D EMIT REPEAT
  BEGIN DUP 400 >= WHILE 400 - S" CD" TYPE REPEAT
  BEGIN DUP 100 >= WHILE 100 - CHAR C EMIT REPEAT
  BEGIN DUP 90 >= WHILE 90 - S" XC" TYPE REPEAT
  BEGIN DUP 50 >= WHILE 50 - CHAR L EMIT REPEAT
  BEGIN DUP 40 >= WHILE 40 - S" XL" TYPE REPEAT
  BEGIN DUP 10 >= WHILE 10 - CHAR X EMIT REPEAT
  BEGIN DUP 9 >= WHILE 9 - S" IX" TYPE REPEAT
  BEGIN DUP 5 >= WHILE 5 - CHAR V EMIT REPEAT
  BEGIN DUP 4 >= WHILE 4 - S" IV" TYPE REPEAT
  BEGIN DUP 1 >= WHILE 1 - CHAR I EMIT REPEAT
  DROP ;

