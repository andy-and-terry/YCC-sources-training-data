\ DO LOOP with LEAVE, +LOOP and nested index J
: FIND-FIRST-SQUARE-OVER ( limit -- n )
  1 BEGIN 2DUP DUP * < 0= WHILE 1+ REPEAT NIP ;

: FIRST-MULTIPLE-OF-7 ( -- n )
  0 100 1 DO I 7 MOD 0= IF DROP I LEAVE THEN LOOP ;

: COUNTDOWN ( n -- )  0 SWAP DO I . -1 +LOOP CR ;

: TABLE ( -- )
  4 1 DO
    4 1 DO I J * 3 .R LOOP CR
  LOOP ;

50 FIND-FIRST-SQUARE-OVER . CR
FIRST-MULTIPLE-OF-7 . CR
