VARIABLE TOTAL
VARIABLE SIGN

: ALT-DIGIT-SUM ( n -- sum )
  0 TOTAL !  1 SIGN !
  BEGIN DUP 0> WHILE
    10 /MOD SWAP                \ rest digit
    SIGN @ * TOTAL +!
    SIGN @ NEGATE SIGN !
  REPEAT
  DROP TOTAL @ ;

1234 DUP . ALT-DIGIT-SUM . CR
99999 DUP . ALT-DIGIT-SUM . CR
1000 DUP . ALT-DIGIT-SUM . CR
