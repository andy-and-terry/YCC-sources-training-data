8 CONSTANT FT-SIZE
CREATE BIT FT-SIZE 1+ CELLS ALLOT
VARIABLE FT-IDX
VARIABLE FT-DELTA
VARIABLE FT-SUM

: BIT-ADDR ( i -- addr ) CELLS BIT + ;

: LOWBIT ( i -- lowbit ) DUP NEGATE AND ;

: FT-INIT ( -- )
  FT-SIZE 1+ 0 DO
    0 I BIT-ADDR !
  LOOP ;

: FT-UPDATE ( i delta -- )
  FT-DELTA ! FT-IDX !
  BEGIN
    FT-SIZE FT-IDX @ >=
  WHILE
    FT-IDX @ BIT-ADDR DUP @ FT-DELTA @ + SWAP !
    FT-IDX @ LOWBIT FT-IDX @ + FT-IDX !
  REPEAT ;

: FT-QUERY ( i -- sum )
  FT-IDX !
  0 FT-SUM !
  BEGIN
    FT-IDX @ 0 >
  WHILE
    FT-SUM @ FT-IDX @ BIT-ADDR @ + FT-SUM !
    FT-IDX @ LOWBIT NEGATE FT-IDX @ + FT-IDX !
  REPEAT
  FT-SUM @ ;

: FT-RANGE-SUM ( lo hi -- sum )
  >R 1- FT-QUERY R> FT-QUERY SWAP - ;

