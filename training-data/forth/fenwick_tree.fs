8 CONSTANT TREE-SIZE
CREATE TREE TREE-SIZE 1+ CELLS ALLOT

: TREE@ ( i -- addr ) CELLS TREE + ;

: INIT-TREE ( -- )
  TREE-SIZE 1+ 0 DO 0 I TREE@ ! LOOP ;

: FT-ADD ( index delta -- )
  SWAP 1+
  BEGIN
    DUP TREE-SIZE <=
  WHILE
    2DUP TREE@ +!
    DUP NEGATE OVER AND +
  REPEAT
  2DROP ;

: FT-PREFIX-SUM ( index -- sum )
  1+ 0 SWAP
  BEGIN
    DUP 0>
  WHILE
    2DUP TREE@ @ ROT + SWAP
    DUP NEGATE OVER AND -
  REPEAT
  DROP ;

: FT-RANGE-SUM ( left right -- sum )
  DUP FT-PREFIX-SUM
  SWAP 1- DUP 0>= IF FT-PREFIX-SUM ELSE DROP 0 THEN
  - ;

INIT-TREE
0 1 FT-ADD
1 3 FT-ADD
2 5 FT-ADD
3 7 FT-ADD
4 9 FT-ADD
5 11 FT-ADD
1 3 FT-RANGE-SUM . CR
0 5 FT-PREFIX-SUM . CR
