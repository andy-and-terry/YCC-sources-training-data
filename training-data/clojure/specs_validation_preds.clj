(require '[clojure.spec.alpha :as s])
(s/def ::age (s/and int? #(<= 0 % 150)))
(s/def ::name (s/and string? seq))
(s/def ::person (s/keys :req-un [::name ::age]))
(println (s/valid? ::age 30) (s/valid? ::age -1) (s/valid? ::person {:name "Ada" :age 36}))
(println (s/conform (s/cat :a int? :b string?) [1 "x"]))
(println (s/valid? (s/coll-of int? :min-count 1) [1 2]) (s/valid? (s/nilable string?) nil))
(println (some? (s/explain-data ::person {:name "" :age 1})))
(println (s/valid? (s/or :n number? :s string?) "str"))
