words = ~w(apple avocado banana blueberry cherry apricot)

IO.inspect(Enum.group_by(words, &String.first/1))
IO.inspect(Enum.frequencies_by(words, &String.first/1))
IO.inspect(Enum.chunk_every(1..7, 3))
