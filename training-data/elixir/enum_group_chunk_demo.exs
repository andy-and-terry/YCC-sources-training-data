IO.inspect(Enum.chunk_every(1..5, 2, 1, :discard))
IO.inspect(Enum.split_with(1..10, &(rem(&1, 3) == 0)))
IO.inspect(Enum.min_max([4, 9, 2, 7]))
IO.inspect(Enum.max_by(words, &String.length/1))
IO.inspect(Enum.sort_by(words, &{-String.length(&1), &1}))
IO.inspect(Enum.uniq_by(words, &String.first/1))
