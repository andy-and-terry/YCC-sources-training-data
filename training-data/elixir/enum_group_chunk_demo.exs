words = ~w(apple avocado banana blueberry cherry apricot)

IO.inspect(Enum.group_by(words, &String.first/1))
IO.inspect(Enum.group_by(words, &String.length/1, &String.upcase/1))
IO.inspect(Enum.chunk_every(1..10, 4))
IO.inspect(Enum.chunk_every(1..6, 3, 1, :discard))
IO.inspect(Enum.chunk_by([1, 1, 2, 3, 3, 3, 1], & &1))
IO.inspect(Enum.frequencies(words |> Enum.map(&String.first/1)))
IO.inspect(Enum.split_with(1..10, &(rem(&1, 3) == 0)))
IO.inspect(Enum.zip([1, 2, 3], [:a, :b, :c]))
IO.inspect(Enum.unzip([{1, :a}, {2, :b}]))
IO.inspect(Enum.with_index(words, 1) |> Enum.take(2))
IO.inspect(Enum.min_max([4, 9, 1]))
IO.inspect(Enum.dedup([1, 1, 2, 2, 1]))
IO.inspect(Enum.take_every(1..10, 3))
